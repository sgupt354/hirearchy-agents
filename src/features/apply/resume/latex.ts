import type { Entry } from './profile';
import type { TailoredResume } from './tailor';

// One-page LaTeX resume. Every piece of student text goes through escapeLatex, so a "C# & 100% of $" bullet can't
// break compilation. Uses only packages every TeX distribution (and Overleaf) ships.

const SPECIAL: Record<string, string> = {
  '\\': '\\textbackslash{}',
  '&': '\\&',
  '%': '\\%',
  $: '\\$',
  '#': '\\#',
  _: '\\_',
  '{': '\\{',
  '}': '\\}',
  '~': '\\textasciitilde{}',
  '^': '\\textasciicircum{}',
};

/** Escape every LaTeX special character in one pass (so a replacement is never escaped twice). */
export function escapeLatex(s: string): string {
  return s.replace(/[\\&%$#_{}~^]/g, (c) => SPECIAL[c]);
}

const e = escapeLatex;

function entry(x: Entry): string {
  const head = `\\textbf{${e(x.title)}}${x.dates ? ` \\hfill ${e(x.dates)}` : ''}`;
  const sub = x.org || x.location ? `\\\\\n\\textit{${e(x.org)}}${x.location ? ` \\hfill \\textit{${e(x.location)}}` : ''}` : '';
  const bullets = x.bullets.length ? `\n\\begin{itemize}\n${x.bullets.map((b) => `  \\item ${e(b)}`).join('\n')}\n\\end{itemize}` : '';
  return `${head}${sub}${bullets}\n`;
}

function section(title: string, items: Entry[]): string {
  if (!items.length) return '';
  return `\\resumesection{${title}}\n${items.map(entry).join('\\vspace{3pt}\n')}`;
}

export function renderLatex(r: TailoredResume): string {
  const contact = [r.profile.email, r.profile.phone, ...r.profile.links].filter(Boolean).map(e).join(' \\textbar{} ');
  return `% Generated by Hirearchy from the student's own profile. Edit freely.
\\documentclass[10pt,letterpaper]{article}
\\usepackage[T1]{fontenc}
\\usepackage[utf8]{inputenc}
\\usepackage[margin=0.5in]{geometry}
\\usepackage{enumitem}
\\pagestyle{empty}
\\setlength{\\parindent}{0pt}
\\setlist[itemize]{leftmargin=1.2em,itemsep=1pt,topsep=2pt,parsep=0pt}
\\newcommand{\\resumesection}[1]{\\vspace{6pt}{\\large\\bfseries #1}\\\\[-7pt]\\rule{\\linewidth}{0.4pt}\\\\[2pt]}

\\begin{document}
\\begin{center}
{\\LARGE\\bfseries ${e(r.profile.name)}}\\\\[3pt]
${contact}
\\end{center}

${section('Education', r.education)}
${section('Experience', r.experience)}
${section('Projects', r.projects)}
${r.skills.length ? `\\resumesection{Skills}\n${r.skills.map(e).join(', ')}\n` : ''}
\\end{document}
`;
}

/** "Resume - Stripe - Software Engineer Intern" (no characters that break file systems). */
export function resumeFileName(company: string, role: string): string {
  const clean = (s: string) => s.replace(/[\\/:*?"<>|]+/g, ' ').replace(/\s+/g, ' ').trim();
  return `Resume - ${clean(company) || 'Company'} - ${clean(role) || 'Role'}`;
}

/** Fields for Overleaf's documented "open in Overleaf" form (POST https://www.overleaf.com/docs). */
export function overleafFields(tex: string, fileName: string): Record<string, string> {
  return { encoded_snip: encodeURIComponent(tex), snip_name: `${fileName}.tex` };
}

